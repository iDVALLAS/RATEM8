const PREFIX: [string, string][] = [
  ["contacts.import.", "Imported contacts"],
  ["contacts.tags.", "Changed tags"],
  ["campaign.", "Changed a campaign"],
  ["gate.send.", "Sent a message"],
  ["gate.block.", "The contact rules held a message"],
  ["loa.", "LOA activity"],
  ["mfa.", "Sign-in code activity"],
  ["passkey.", "Face ID activity"],
];

/** A code like "contacts.import.finish" in plain words. */
export function activityLabel(code: string): string {
  if (EXACT[code]) return EXACT[code];
  const hit = PREFIX.find(([p]) => code.startsWith(p));
  if (hit) return hit[1];
  const words = code.replace(/[._]+/g, " ").trim();
  return words ? `Other: ${words}` : "Other activity";
}
